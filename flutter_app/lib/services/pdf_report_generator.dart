      widgets.add(
        pw.TableHelper.fromTextArray(
          border: pw.TableBorder.all(color: _border, width: 0.5),
          headerStyle: pw.TextStyle(color: _textPrimary, fontWeight: pw.FontWeight.bold, fontSize: 8),
