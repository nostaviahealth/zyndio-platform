              m.value,
              m.unit,
              m.range,
              m.status,
            ]),
          ],
        ),
      );
      widgets.add(pw.SizedBox(height: 16));
    }
    return widgets;
  }

  static List<pw.Widget> _buildWearableVitalsSection(HealthDataSnapshot snapshot) {
    final vitals = snapshot.vitalTrends;
    if (vitals.isEmpty) return [];

    // Compute averages
    double avg(List<double?> vals) {
      final valid = vals.whereType<double>().toList();
      if (valid.isEmpty) return 0;
      return valid.reduce((a, b) => a + b) / valid.length;
    }

    String calcRange(List<double?> vals) {
      final valid = vals.whereType<double>().toList();
      if (valid.isEmpty) return '--';
      return '${valid.reduce(math.min).toStringAsFixed(0)}–${valid.reduce(math.max).toStringAsFixed(0)}';
    }

    final avgSteps = avg(vitals.map((v) => v.steps?.toDouble()).toList()).toStringAsFixed(0);
    final avgHR = avg(vitals.map((v) => v.avgHeartRate).toList()).toStringAsFixed(0);
    final avgHRV = avg(vitals.map((v) => v.avgHrv).toList()).toStringAsFixed(1);
    final avgRHR = avg(vitals.map((v) => v.restingHeartRate).toList()).toStringAsFixed(0);
    final avgSpO2 = avg(vitals.map((v) => v.spo2).toList()).toStringAsFixed(1);
    final avgRR = avg(vitals.map((v) => v.respiratoryRate).toList()).toStringAsFixed(1);
    final avgVO2 = avg(vitals.map((v) => v.vo2Max).toList()).toStringAsFixed(1);
    final avgTemp = avg(vitals.map((v) => v.skinTemp).toList()).toStringAsFixed(1);

    final hrTrend = vitals.map((v) => v.avgHeartRate ?? 72.0).toList();

    return [
      _buildSectionTitle('Wearable Vitals & Trends'),
      pw.Row(children: [
        _buildMetricCard('Avg Steps', avgSteps, 'steps', range: calcRange(vitals.map((v) => v.steps?.toDouble()).toList())),
        _buildMetricCard('Avg HR', avgHR, 'bpm', range: calcRange(vitals.map((v) => v.avgHeartRate).toList())),
        _buildMetricCard('Avg HRV', avgHRV, 'ms', range: calcRange(vitals.map((v) => v.avgHrv).toList())),
        _buildMetricCard('Avg RHR', avgRHR, 'bpm', range: calcRange(vitals.map((v) => v.restingHeartRate).toList())),
      ]),
      pw.SizedBox(height: 6),
      pw.Row(children: [
        _buildMetricCard('Avg SpO2', avgSpO2, '%', range: calcRange(vitals.map((v) => v.spo2).toList())),
        _buildMetricCard('Avg RR', avgRR, 'rpm', range: calcRange(vitals.map((v) => v.respiratoryRate).toList())),
        _buildMetricCard('VO2 Max', avgVO2, 'mL/kg/min'),
        _buildMetricCard('Skin Temp', avgTemp, '°C', range: calcRange(vitals.map((v) => v.skinTemp).toList())),
      ]),
      pw.SizedBox(height: 16),
      pw.Text('Heart Rate Trend (${vitals.length} days)', style: pw.TextStyle(color: _textPrimary, fontSize: 11)),
      pw.SizedBox(height: 8),
      pw.Container(
        padding: const pw.EdgeInsets.all(10),
        decoration: pw.BoxDecoration(color: _cardBg, border: pw.Border.all(color: _border), borderRadius: const pw.BorderRadius.all(pw.Radius.circular(4))),
        child: _buildSparkline(hrTrend, _primary, 430, 60),
      ),
    ];
  }

  static List<pw.Widget> _buildSleepAnalysisSection(HealthDataSnapshot snapshot) {
    final sleep = snapshot.sleepTrends;
    if (sleep.isEmpty) return [];

    double avg(List<double?> vals) {
      final valid = vals.whereType<double>().toList();
      if (valid.isEmpty) return 0;
      return valid.reduce((a, b) => a + b) / valid.length;
    }

    final avgScore = avg(sleep.map((s) => s.sleepScore?.toDouble()).toList()).toStringAsFixed(0);
    final avgHours = avg(sleep.map((s) => s.totalHours).toList()).toStringAsFixed(1);
    final avgEff = avg(sleep.map((s) => s.efficiency).toList()).toStringAsFixed(0);
    final avgDeep = avg(sleep.map((s) => s.deepSleepHours).toList()).toStringAsFixed(1);
    final avgREM = avg(sleep.map((s) => s.remSleepHours).toList()).toStringAsFixed(1);
    final avgLight = avg(sleep.map((s) => s.lightSleepHours).toList()).toStringAsFixed(1);
    final avgAwake = avg(sleep.map((s) => s.awakeHours).toList()).toStringAsFixed(1);

    final nightlyDurations = sleep.map((s) => s.totalHours ?? 7.0).toList();

    return [
      _buildSectionTitle('Sleep Analysis'),
      pw.Row(children: [
        _buildMetricCard('Sleep Score', avgScore, ''),
        _buildMetricCard('Total Hours', avgHours, 'hrs'),
        _buildMetricCard('Efficiency', avgEff, '%'),
      ]),
      pw.SizedBox(height: 12),
      pw.Text('Sleep Stages (Average Hours)', style: pw.TextStyle(color: _textPrimary, fontSize: 11)),
      pw.SizedBox(height: 6),
      pw.Container(
        padding: const pw.EdgeInsets.all(10),
        decoration: pw.BoxDecoration(color: _cardBg, border: pw.Border.all(color: _border), borderRadius: const pw.BorderRadius.all(pw.Radius.circular(4))),
        child: pw.Row(
          mainAxisAlignment: pw.MainAxisAlignment.spaceAround,
          children: [
            _buildSleepStage('Deep', '${avgDeep}h', PdfColor.fromHex('#8B5CF6')),
            _buildSleepStage('REM', '${avgREM}h', PdfColor.fromHex('#06B6D4')),
            _buildSleepStage('Light', '${avgLight}h', PdfColor.fromHex('#3B82F6')),
            _buildSleepStage('Awake', '${avgAwake}h', PdfColor.fromHex('#F59E0B')),
          ],
        ),
      ),
      pw.SizedBox(height: 12),
      pw.Text('Nightly Sleep Duration', style: pw.TextStyle(color: _textPrimary, fontSize: 11)),
      pw.SizedBox(height: 8),
      pw.Container(
        height: 80,
        width: double.infinity,
        padding: const pw.EdgeInsets.all(8),
        decoration: pw.BoxDecoration(color: _cardBg, border: pw.Border.all(color: _border), borderRadius: const pw.BorderRadius.all(pw.Radius.circular(4))),
        child: pw.CustomPaint(
          painter: (PdfGraphics canvas, PdfPoint size) {
            final durations = nightlyDurations;
            if (durations.isEmpty) return;
            final barWidth = (size.x / durations.length) * 0.55;
            final maxDur = durations.reduce(math.max);
            if (maxDur == 0) return;

            for (var i = 0; i < durations.length; i++) {
              final h = (durations[i] / maxDur) * size.y * 0.9;
              final x = i * (size.x / durations.length) + (size.x / durations.length - barWidth) / 2;
              final y = h;

              canvas.setFillColor(_primary);
              canvas.drawRect(x, 0, barWidth, y);
              canvas.fillPath();
            }
          },
        ),
      ),
    ];
  }

  static pw.Widget _buildSleepStage(String label, String value, PdfColor color) {
    return pw.Column(
      children: [
        pw.Container(width: 8, height: 8, decoration: pw.BoxDecoration(color: color, shape: pw.BoxShape.circle)),
        pw.SizedBox(height: 4),
        pw.Text(value, style: pw.TextStyle(color: _textPrimary, fontSize: 12, fontWeight: pw.FontWeight.bold)),
        pw.Text(label, style: pw.TextStyle(color: _textSecondary, fontSize: 9)),
      ],
    );
  }

  static List<pw.Widget> _buildNutritionSection(HealthDataSnapshot snapshot) {
    final nutrition = snapshot.nutritionTrends;
    if (nutrition.isEmpty) return [];

    double avg(List<int?> vals) {
      final valid = vals.whereType<int>().toList();
      if (valid.isEmpty) return 0;
      return valid.reduce((a, b) => a + b) / valid.length;
    }

    final avgCal = avg(nutrition.map((n) => n.calories).toList()).toStringAsFixed(0);
    final avgProt = avg(nutrition.map((n) => n.proteinG).toList()).toStringAsFixed(0);
    final avgCarbs = avg(nutrition.map((n) => n.carbsG).toList()).toStringAsFixed(0);
    final avgFat = avg(nutrition.map((n) => n.fatG).toList()).toStringAsFixed(0);
    final avgFiber = avg(nutrition.map((n) => n.fiberG).toList()).toStringAsFixed(0);

    return [
      _buildSectionTitle('Nutrition & Diet'),
      pw.Row(children: [
        _buildMetricCard('Calories', avgCal, 'kcal'),
        _buildMetricCard('Protein', avgProt, 'g'),
        _buildMetricCard('Carbs', avgCarbs, 'g'),
      ]),
      pw.SizedBox(height: 6),
      pw.Row(children: [
        _buildMetricCard('Fat', avgFat, 'g'),
        _buildMetricCard('Fiber', avgFiber, 'g'),
        pw.Expanded(child: pw.SizedBox()),
      ]),
      pw.SizedBox(height: 12),
      pw.Text('Targets vs Actuals', style: pw.TextStyle(color: _textPrimary, fontSize: 12, fontWeight: pw.FontWeight.bold)),
      pw.SizedBox(height: 8),
      pw.TableHelper.fromTextArray(
        border: pw.TableBorder.all(color: _border, width: 0.5),
        headerStyle: pw.TextStyle(color: _textPrimary, fontWeight: pw.FontWeight.bold, fontSize: 9),
        headerDecoration: pw.BoxDecoration(color: _cardBg),
        cellStyle: pw.TextStyle(color: _textPrimary, fontSize: 9),
        cellPadding: const pw.EdgeInsets.all(6),
        data: [
          ['Metric', 'Daily Target', 'Daily Average'],
          ['Calories', '${snapshot.dailyCalorieTarget ?? "--"} kcal', '$avgCal kcal'],
          ['Protein', '${snapshot.dailyProteinTarget ?? "--"} g', '$avgProt g'],
          ['Carbs', '${snapshot.dailyCarbsTarget ?? "--"} g', '$avgCarbs g'],
          ['Fat', '${snapshot.dailyFatTarget ?? "--"} g', '$avgFat g'],
        ],
      ),
    ];
  }

