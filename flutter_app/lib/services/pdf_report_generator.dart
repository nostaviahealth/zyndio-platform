    if (reports.isEmpty) return [];

    final widgets = <pw.Widget>[_buildSectionTitle('Lab Reports & Biomarkers')];

    for (final report in reports) {
      widgets.add(
        pw.Text(
          '${report.title} — ${report.date}',
