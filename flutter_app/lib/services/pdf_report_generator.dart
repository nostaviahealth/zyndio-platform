import 'dart:typed_data';
import 'dart:math' as math;
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:intl/intl.dart';
import '../models/health_data_snapshot.dart';

class PdfReportGenerator {
  // Color scheme
  static final PdfColor _primary = PdfColor.fromHex('#6366F1');
  static final PdfColor _danger = PdfColor.fromHex('#EF4444');
  static final PdfColor _darkBg = PdfColor.fromHex('#0F172A');
  static final PdfColor _cardBg = PdfColor.fromHex('#1E293B');
  static final PdfColor _textPrimary = PdfColor.fromHex('#F8FAFC');
  static final PdfColor _textSecondary = PdfColor.fromHex('#94A3B8');
  static final PdfColor _border = PdfColor.fromHex('#334155');

  static Future<Uint8List> generateReport(HealthDataSnapshot snapshot) async {
    final pdf = pw.Document(
      theme: pw.ThemeData.withFont(
        base: pw.Font.helvetica(),
        bold: pw.Font.helveticaBold(),
        italic: pw.Font.helveticaOblique(),
      ),
    );

    final pageFormat = PdfPageFormat.a4;
    final pageMargin = const pw.EdgeInsets.symmetric(horizontal: 40, vertical: 30);

    // Page 1: Cover & Executive Summary (Single page)
    pdf.addPage(
      pw.Page(
        pageTheme: _buildPageTheme(pageFormat, pageMargin),
        build: (context) {
          return pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              _buildHeader(snapshot.hospitalBrandName),
              pw.SizedBox(height: 40),
              pw.Text(
                'Comprehensive Health Report',
                style: pw.TextStyle(color: _primary, fontSize: 26, fontWeight: pw.FontWeight.bold),
              ),
              pw.SizedBox(height: 8),
              pw.Container(
                padding: const pw.EdgeInsets.symmetric(horizontal: 12, vertical: 6),
                decoration: pw.BoxDecoration(
                  color: _primary.shade(0.8),
                  borderRadius: const pw.BorderRadius.all(pw.Radius.circular(20)),
                ),
                child: pw.Text(
                  'Clinician-Ready Health Passport',
                  style: pw.TextStyle(color: _primary, fontSize: 10, fontWeight: pw.FontWeight.bold),
                ),
              ),
              pw.SizedBox(height: 30),

              if (snapshot.sections.demographics) ...[
                pw.Text(
                  'Patient: ${snapshot.patientName}',
                  style: pw.TextStyle(color: _textPrimary, fontSize: 18, fontWeight: pw.FontWeight.bold),
                ),
                pw.SizedBox(height: 4),
                pw.Text(
                  'Age: ${snapshot.age ?? "N/A"} | Gender: ${snapshot.gender ?? "N/A"} | Goal: ${snapshot.primaryGoal ?? "N/A"}',
                  style: pw.TextStyle(color: _textSecondary, fontSize: 12),
                ),
                pw.SizedBox(height: 6),
                pw.Text(
                  'Date Range: ${snapshot.dateRange.label} (${DateFormat.yMMMd().format(snapshot.dateRange.start)} — ${DateFormat.yMMMd().format(snapshot.dateRange.end)})',
                  style: pw.TextStyle(color: _textSecondary, fontSize: 11),
                ),
                pw.Text(
                  'Generated: ${DateFormat.yMMMd().add_jm().format(snapshot.generatedAt)}',
                  style: pw.TextStyle(color: _textSecondary, fontSize: 11),
                ),
              ],
              pw.SizedBox(height: 40),

              // Big metric cards
              pw.Row(
                mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                children: [
                  _buildBigNumberCard(
                    'Biological Age',
                    '${snapshot.biologicalAge ?? snapshot.bioAge ?? "--"}',
                    'vs Chronological: ${snapshot.age ?? "--"}',
                  ),
                  _buildBigNumberCard(
                    'Longevity Score',
                    '${snapshot.overallLongevityScore ?? "--"}',
                    'Overall Intelligence',
                  ),
                  _buildBigNumberCard(
                    'Health Grade',
                    snapshot.healthGrade ?? '--',
                    'Pace: ${snapshot.paceOfAging?.toStringAsFixed(2) ?? "N/A"}',
                  ),
                ],
              ),

              pw.SizedBox(height: 30),
              pw.Divider(color: _border),
              pw.SizedBox(height: 10),
              pw.Center(
                child: pw.Text(
                  'Generated by Zyndio Intelligence Engine',
                  style: pw.TextStyle(color: _textSecondary, fontSize: 10),
                ),
              ),
            ],
          );
        },
      ),
    );

    // MultiPage for all data sections
    pdf.addPage(
      pw.MultiPage(
        maxPages: 100,
        pageTheme: _buildPageTheme(pageFormat, pageMargin),
        header: (context) => _buildCompactHeader(snapshot.hospitalBrandName),
        footer: (context) => _buildFooter(context),
        build: (context) {
          return [
            if (snapshot.sections.intelligence)
              ..._buildIntelligenceSection(snapshot),

            if (snapshot.sections.labReports && snapshot.labReports.isNotEmpty)
              ..._buildLabReportsSection(snapshot),

            if (snapshot.sections.wearableVitals && snapshot.vitalTrends.isNotEmpty)
              ..._buildWearableVitalsSection(snapshot),

            if (snapshot.sections.sleepAnalysis && snapshot.sleepTrends.isNotEmpty)
              ..._buildSleepAnalysisSection(snapshot),

            if (snapshot.sections.nutrition && snapshot.nutritionTrends.isNotEmpty)
              ..._buildNutritionSection(snapshot),

            if (snapshot.sections.protocols && snapshot.protocols.isNotEmpty)
              ..._buildProtocolsSection(snapshot),

            if (snapshot.sections.questionnaireBaseline && snapshot.questionnaire != null)
              ..._buildQuestionnaireSection(snapshot),

            ..._buildDisclaimerSection(snapshot),
          ];
        },
      ),
    );

    return pdf.save();
  }

  // ─── Theme ──────────────────────────────────────────────────────

  static pw.PageTheme _buildPageTheme(PdfPageFormat format, pw.EdgeInsets margin) {
    return pw.PageTheme(
      pageFormat: format,
      margin: margin,
      theme: pw.ThemeData(
        defaultTextStyle: pw.TextStyle(color: _textPrimary, fontSize: 12),
      ),
      buildBackground: (context) => pw.FullPage(
        ignoreMargins: true,
        child: pw.Container(color: _darkBg),
      ),
    );
  }

