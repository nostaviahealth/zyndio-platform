  static pw.Widget _buildSparkline(List<double> values, PdfColor color, double width, double height) {
    if (values.isEmpty || values.length < 2) return pw.SizedBox(width: width, height: height);

    final maxVal = values.reduce(math.max);
    final minVal = values.reduce(math.min);
    final range = maxVal - minVal;
    if (range == 0) return pw.SizedBox(width: width, height: height);

    return pw.SizedBox(
      width: width,
      height: height,
      child: pw.CustomPaint(
        painter: (PdfGraphics canvas, PdfPoint size) {
          final w = size.x;
          final h = size.y;
          final dx = w / (values.length - 1);

          // Draw line
          canvas.setStrokeColor(color);
          canvas.setLineWidth(1.5);
          for (var i = 0; i < values.length; i++) {
            final x = i * dx;
            final y = ((values[i] - minVal) / range) * (h * 0.85) + h * 0.05;
            if (i == 0) {
              canvas.moveTo(x, y);
            } else {
              canvas.lineTo(x, y);
            }
          }
          canvas.strokePath();

          // Draw dots
          canvas.setFillColor(color);
          for (var i = 0; i < values.length; i++) {
            final x = i * dx;
            final y = ((values[i] - minVal) / range) * (h * 0.85) + h * 0.05;
            canvas.drawEllipse(x, y, 2, 2);
            canvas.fillPath();
          }
        },
      ),
    );
  }

