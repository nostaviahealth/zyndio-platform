// M8 (Henry ruling + OBSERVED.md probe): password_requirements and
// secure_password_change. These assertions match what
// work/.claude-runs/tc005/m8/OBSERVED.md actually recorded against local
// GoTrue - see that file for the raw probe output. Nothing here is invented
// for behaviour that wasn't observed.
import { describe, it, expect, afterEach } from 'vitest';
import { integrationEnvReady } from './setup';
import { anonSignIn, callFn, createUser, deleteUser, signIn } from './helpers';

const SUPABASE_URL = process.env.SUPABASE_URL;
const SUPABASE_ANON_KEY = process.env.SUPABASE_ANON_KEY;

function directPasswordChange(accessToken: string, password: string) {
  return fetch(`${SUPABASE_URL}/auth/v1/user`, {
    method: 'PUT',
    headers: {
      'Content-Type': 'application/json',
      apikey: SUPABASE_ANON_KEY!,
      Authorization: `Bearer ${accessToken}`,
    },
    body: JSON.stringify({ password }),
  });
}

describe.skipIf(!integrationEnvReady)('password hardening (M8)', () => {
  const cleanup: string[] = [];
  afterEach(async () => {
    while (cleanup.length) await deleteUser(cleanup.pop()!);
  });

  it('GoTrue rejects a short password on a direct password change', async () => {
    const user = await createUser('tc005-pw-short');
    cleanup.push(user.userId);

    const aal1 = await signIn(user.email, user.password);
    const res = await directPasswordChange(aal1.access_token!, 'short');
    const body = (await res.json()) as { error_code?: string };

    expect(res.status).toBe(422);
    expect(body.error_code).toBe('weak_password');
  });

  it.each([
    ['no symbol', 'Longpassword1'],
    ['no uppercase', 'longpassword1!'],
    ['no lowercase', 'LONGPASSWORD1!'],
    ['no digit', 'Longpassword!!'],
  ])('GoTrue rejects a long password missing a character class (%s)', async (_label, candidate) => {
    const user = await createUser('tc005-pw-class');
    cleanup.push(user.userId);

    const aal1 = await signIn(user.email, user.password);
    const res = await directPasswordChange(aal1.access_token!, candidate);
    const body = (await res.json()) as { error_code?: string };

    expect(res.status).toBe(422);
    expect(body.error_code).toBe('weak_password');
  });

  it('GoTrue accepts a password that meets every character class, even if not signed in via our function', async () => {
    const user = await createUser('tc005-pw-ok');
    cleanup.push(user.userId);

    const aal1 = await signIn(user.email, user.password);
    const res = await directPasswordChange(aal1.access_token!, 'Zq7!fictional-pass');
    expect(res.status).toBe(200);

    const signedIn = await anonSignIn(user.email, 'Zq7!fictional-pass');
    expect(signedIn.status).toBe(200);
  });

  // OBSERVED.md section 1: this is the accepted gap (TC-011), not a bug this
  // card fixes. A *fresh* session can still bypass our blocklist and audit
  // log by calling GoTrue directly instead of the change-password function.
  it('ACCEPTED GAP: a fresh session can set a blocklisted (but character-valid) password via direct GoTrue update, bypassing our blocklist', async () => {
    const user = await createUser('tc005-pw-gap');
    cleanup.push(user.userId);

    const aal1 = await signIn(user.email, user.password);
    // lower('Chocolate@123') === 'chocolate@123', generated by the
    // blocklist migration (base 'chocolate' + suffix '@123').
    const res = await directPasswordChange(aal1.access_token!, 'Chocolate@123');
    expect(res.status).toBe(200);

    const signedIn = await anonSignIn(user.email, 'Chocolate@123');
    expect(signedIn.status).toBe(200);
  });

  it('the change-password function still refuses the same blocklisted password', async () => {
    const user = await createUser('tc005-pw-fn-blocked');
    cleanup.push(user.userId);

    const aal1 = await signIn(user.email, user.password);
    const res = await callFn('change-password', aal1.access_token!, { password: 'Chocolate@123' });
    const body = (await res.json()) as { error?: string };

    expect(res.status).toBe(400);
    expect(body.error).toBe('password_too_common');
  });
});
